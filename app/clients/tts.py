# ---------- ElevenLabs (облако, казахский) ----------
async def _eleven(text: str, language: str | None) -> bytes:
    """ElevenLabs TTS. Просим PCM и оборачиваем в WAV (пайплайн склеивает WAV).

    ⚠️ Ходит в интернет (api.elevenlabs.io) — в сети АФМ без доступа наружу не
    заработает. Ключ/голос/модель — в .env (ELEVENLABS_*).
    """
    import httpx
    if not (settings.elevenlabs_api_key and settings.elevenlabs_voice_id):
        raise RuntimeError(
            "TTS=eleven, но не заданы ELEVENLABS_API_KEY / ELEVENLABS_VOICE_ID в .env."
        )
    sr = 24000  # PCM 16-бит моно; частоту фиксируем — куски склеиваются одинаковыми
    url = (f"{settings.elevenlabs_url.rstrip('/')}"
           f"/text-to-speech/{settings.elevenlabs_voice_id}?output_format=pcm_{sr}")
    # Два разных таймаута. connect — короткий (ELEVENLABS_CONNECT_TIMEOUT): в
    # сети без выхода наружу пакеты просто гасятся файрволом, и соединение висит
    # до упора — это самый частый способ «облако недоступно», и платить за него
    # полный таймаут нечего. read — полный (ELEVENLABS_TIMEOUT): облако
    # достучалось, значит даём ему спокойно синтезировать длинный кусок.
    timeout = httpx.Timeout(settings.elevenlabs_timeout,
                            connect=settings.elevenlabs_connect_timeout)
    # verify — из настройки: за TLS-прокси АФМ сертификат облака подписан их
    # корнем, которого нет в certifi (см. elevenlabs_verify_ssl). Правильнее
    # дать процессу SSL_CERT_FILE с корнем прокси — httpx его уважает.
    async with httpx.AsyncClient(timeout=timeout,
                                 verify=settings.elevenlabs_verify_ssl) as client:
        resp = await client.post(
            url,
            headers={"xi-api-key": settings.elevenlabs_api_key},
            json={"text": text, "model_id": settings.elevenlabs_model,
                  "voice_settings": {"stability": 0.5, "similarity_boost": 0.8}},
        )
        resp.raise_for_status()
        pcm = resp.content
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm)
    return buf.getvalue()


