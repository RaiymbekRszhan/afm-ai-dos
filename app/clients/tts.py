def _ru_gen_prep_sub(m: "re.Match") -> str:
    core = m.group(2).replace(" ", "").replace(" ", "")
    try:
        words = _num2words(int(core), lang="ru").split()
    except Exception:
        return m.group(0)
    return f"{m.group(1)} " + " ".join(_RU_CARD_GEN.get(w, w) for w in words)


# Проценты после тех же предлогов — тоже родительный: «до 20%» -> «до двадцати
# процентов» (обычное правило процентов дало бы именительный «до двадцать»).
_RU_GEN_PCT_RE = re.compile(
    r"\b(в размере|от|до|свыше|около|более|менее)\s+(\d+)\s*%", re.IGNORECASE)


def _ru_gen_pct_sub(m: "re.Match") -> str:
    n = int(m.group(2))
    try:
        words = [_RU_CARD_GEN.get(w, w) for w in _num2words(n, lang="ru").split()]
    except Exception:
        return m.group(0)
    unit = "процента" if n % 10 == 1 and n % 100 != 11 else "процентов"
    return f"{m.group(1)} {' '.join(words)} {unit}"


def _pct_sub(m: "re.Match") -> str:
    """«20%» -> «двадцать процентов»; «1,5%» -> «одна целая пять десятых процента»."""
    tok = m.group(1)
    if "," in tok:  # дробь -> родительный ед. («процента»)
        return f"{_num2words(float(tok.replace(',', '.')), lang='ru')} процента"
    n = int(tok)
    return f"{_num2words(n, lang='ru')} {_ru_plural(n, 'процент', 'процента', 'процентов')}"


# Телефоны/горячие линии: «по номеру 1458», «телефон 8 800 080 18 90» — читать
# ГРУППАМИ с паузой-запятой между ними: 11 цифр подряд без пауз сливаются в кашу,
# и F5 их комкает. Группу без ведущего нуля читаем числом («800» -> «восемьсот»,
# «18» -> «восемнадцать») — так телефоны диктуют вживую; с ведущим нулём — по
# цифрам («080» -> «ноль восемь ноль»). Слитную запись (87001234567) группируем
# сами: 1-3-3-2-2 (11 цифр) / 3-3-2-2 (10) / 3-2-2 (7).
_RU_DIGIT_WORDS = ["ноль", "один", "два", "три", "четыре", "пять", "шесть",
                   "семь", "восемь", "девять"]
# До двух слов между ключевым словом и цифрами: «по номеру горячей линии 1458»,
# «телефон доверия 1414» — тоже телефоны.
_RU_PHONE_RE = re.compile(
    r"\b((?:номер\w*|тел\.|телефон\w*)(?:\s+[а-яё]+){0,2})\s+(\+?\d[\d\s\-()]{2,17}\d)",
    re.IGNORECASE)
# Телефон БЕЗ слова «номер/телефон»: «+7 777 123 45 67», «8 (800) 080-18-90» —
# префикс +7/8 и 10 цифр группами. Требуем разделитель после префикса, чтобы не
# трогать обычные числа; слитные 87001234567 ловит правило «10+ цифр подряд».
_RU_PHONE_BARE_RE = re.compile(
    r"(?<![\d,])(\+7|8)[\s\-(]+\d{3}[)\s\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\s?\d)")
# Слитные коды из 10+ цифр (сотовый без пробелов, ЖСН/БСН) — по цифрам группами.
# Лукэраунды отсекают продолжение числа и десятичную дробь (3,1415926535…),
# но НЕ точку конца предложения после номера.
_RU_LONG_CODE_RE = re.compile(r"(?<!\d)(?<!\d,)\+?\d{10,}(?!\d)(?!,\d)")


def _ru_digits(s: str) -> str:
    return " ".join(_RU_DIGIT_WORDS[int(d)] for d in s if d.isdigit())


def _ru_phone_group(g: str) -> str:
    """Одна группа цифр телефона: 2–3 цифры без ведущего нуля — числом, иначе по цифрам."""
    if _num2words is not None and 2 <= len(g) <= 3 and not g.startswith("0"):
        return _num2words(int(g), lang="ru")
    return _ru_digits(g)


def _ru_phone_words(raw: str) -> str:
    """Телефон/код -> слова группами через запятую (запятая даёт паузу в TTS)."""
    groups = re.findall(r"\d+", raw)
    if len(groups) == 1:  # слитная запись — группируем сами
        s = groups[0]
        if len(s) == 11:
            groups = [s[:1], s[1:4], s[4:7], s[7:9], s[9:]]
        elif len(s) == 10:
            groups = [s[:3], s[3:6], s[6:8], s[8:]]
        elif len(s) == 7:
            groups = [s[:3], s[3:5], s[5:]]
    words = ", ".join(_ru_phone_group(g) for g in groups)
    return f"плюс {words}" if raw.lstrip().startswith("+") else words


def _ru_phone_sub(m: "re.Match") -> str:
    return f"{m.group(1)} {_ru_phone_words(m.group(2))}"


def _ru_numbers(text: str) -> str:
    """Цифры -> слова. В распознанных контекстах — ПОРЯДКОВЫЕ с согласованием по
    роду/падежу (статья 214 -> «двести четырнадцатая»; в 2024 году -> «...четвёртом
    году»; пунктом 5 -> «пятым»). Телефоны (после «номер/телефон», в форме
    «+7/8 XXX XXX XX XX» и слитные 10+ цифр) — группами с паузами. Остальные
    числа — количественные; % -> процент(а/ов).
    Без num2words — no-op (числа останутся цифрами).
    """
    text = _RU_PHONE_RE.sub(_ru_phone_sub, text)   # номера/телефоны -> группами
    text = _RU_PHONE_BARE_RE.sub(                  # +7/8 ... без слова «номер»
        lambda m: _ru_phone_words(m.group(0)), text)
    text = _RU_LONG_CODE_RE.sub(                   # слитные 10+ цифр (сотовый, ЖСН)
        lambda m: _ru_phone_words(m.group(0)), text)
    if _num2words is None:
        return text
    # Даты — ДО правил предлогов: иначе «до 15 марта» уйдёт в количественный
    # родительный («до пятнадцати марта»).
    text = _RU_DATE_RE.sub(_ord_date_sub, text)    # «1 января» -> «первого января»
    text = _GOV_RE.sub(_ord_gov_sub, text)         # статья/пункт/часть N -> порядковое
    text = _YEAR_RE.sub(_ord_year_sub, text)       # NNNN год/года/году -> порядковое
    text = _RU_GEN_PCT_RE.sub(_ru_gen_pct_sub, text)    # от/до N% -> родительный
    text = _RU_GEN_PREP_RE.sub(_ru_gen_prep_sub, text)  # от/до N -> родительный
    text = re.sub(r"(\d+(?:,\d+)?)\s*%", _pct_sub, text)  # проценты
    text = _FRAC_RE.sub(_ru_frac_sub, text)        # 1/2 -> «одна вторая»
    return _NUM_RE.sub(_num_repl, text)            # остальные числа -> количественные


# --- Дроби через слэш: «1/2 суммы», «2/3 бөлігі» ----------------------------
# Раньше их не было ни в одном языке, хотя в комментариях числились: каждое число
# раскрывалось отдельно, а слэш оставался в тексте, и получалось «один/два части».
# Слэш вслух не читается вовсе, так что дробь превращалась в два числа подряд.
# Знаменатели дальше 12 в юридических текстах не встречаются; что не попало под
# правило — остаётся цифрами (лучше цифра, чем неверное слово).
_FRAC_RE = re.compile(r"(?<![\d,/])(\d{1,2})/(\d{1,2})(?![\d,/])")
# Русские дроби: числитель 1 -> «одна вторая», больше -> «две третьих».
_RU_FRAC_DEN_ONE = {
    2: "вторая", 3: "третья", 4: "четвёртая", 5: "пятая", 6: "шестая",
    7: "седьмая", 8: "восьмая", 9: "девятая", 10: "десятая", 12: "двенадцатая",
}
_RU_FRAC_DEN_MANY = {
    2: "вторых", 3: "третьих", 4: "четвёртых", 5: "пятых", 6: "шестых",
    7: "седьмых", 8: "восьмых", 9: "девятых", 10: "десятых", 12: "двенадцатых",
}
_RU_FRAC_NUM_MANY = {2: "две", 3: "три", 4: "четыре", 5: "пять",
                     6: "шесть", 7: "семь", 8: "восемь", 9: "девять"}


def _ru_frac_sub(m: "re.Match") -> str:
    num, den = int(m.group(1)), int(m.group(2))
    if num == 1 and den in _RU_FRAC_DEN_ONE:
        return f"одна {_RU_FRAC_DEN_ONE[den]}"
    if num in _RU_FRAC_NUM_MANY and den in _RU_FRAC_DEN_MANY:
        return f"{_RU_FRAC_NUM_MANY[num]} {_RU_FRAC_DEN_MANY[den]}"
    return m.group(0)


# Казахские дроби читаются «знаменатель в исходном падеже + числитель»:
# 2/3 = «үштен екі». Тот же приём уже используется для десятичных
# (_KK_FRAC_PLACE: «нөл бүтін оннан бес»), поэтому форма привычная на слух.
_KK_FRAC_DEN = {
    2: "екіден", 3: "үштен", 4: "төрттен", 5: "бестен", 6: "алтыдан",
    7: "жетіден", 8: "сегізден", 9: "тоғыздан", 10: "оннан", 12: "он екіден",
}


def _kk_frac_sub(m: "re.Match") -> str:
    num, den = int(m.group(1)), int(m.group(2))
    words = _kk_cardinal(num)
    if den in _KK_FRAC_DEN and words:
        return f"{_KK_FRAC_DEN[den]} {words}"
    return m.group(0)


# --- Числа на казахском: цифры -> слова -----------------------------------
# num2words казахский НЕ умеет (NotImplementedError), поэтому конвертер свой.
# Используется и без num2words: для kk цифры всегда озвучиваются.
_KK_ONES = ["", "бір", "екі", "үш", "төрт", "бес", "алты", "жеті", "сегіз", "тоғыз"]
_KK_TENS = ["", "он", "жиырма", "отыз", "қырық", "елу", "алпыс", "жетпіс", "сексен", "тоқсан"]
_KK_SCALE = ["", "мың", "миллион", "миллиард", "триллион"]
_KK_FRAC_PLACE = {1: "оннан", 2: "жүзден", 3: "мыңнан"}  # дробь: «бүтін оннан бес»
_KK_LET = "А-Яа-яЁёӘәІіҢңҒғҮүҰұҚқӨөҺһ"
# Порядковая форма ПОСЛЕДНЕГО слова числа (остальные слова не меняются).
_KK_ORDINAL_LAST = {
    "бір": "бірінші", "екі": "екінші", "үш": "үшінші", "төрт": "төртінші",
    "бес": "бесінші", "алты": "алтыншы", "жеті": "жетінші", "сегіз": "сегізінші",
    "тоғыз": "тоғызыншы", "он": "оныншы", "жиырма": "жиырмасыншы",
    "отыз": "отызыншы", "қырық": "қырқыншы", "елу": "елуінші", "алпыс": "алпысыншы",
    "жетпіс": "жетпісінші", "сексен": "сексенінші", "тоқсан": "тоқсаныншы",
    "жүз": "жүзінші", "мың": "мыңыншы", "миллион": "миллионыншы",
    "миллиард": "миллиардыншы", "триллион": "триллионыншы",
}


def _kk_triple(n: int) -> list[str]:
    """0..999 -> слова (жүз/ондық/бірлік)."""
    words: list[str] = []
    h, rem = divmod(n, 100)
    if h:
        words.append("жүз" if h == 1 else f"{_KK_ONES[h]} жүз")
    t, o = divmod(rem, 10)
    if t:
        words.append(_KK_TENS[t])
    if o:
        words.append(_KK_ONES[o])
    return words


def _kk_cardinal(n: int) -> str | None:
    """Целое -> количественное (50000 -> 'елу мың'). None — если слишком большое."""
    if n == 0:
        return "нөл"
    neg = n < 0
    n = abs(n)
    groups: list[int] = []
    while n:
        n, r = divmod(n, 1000)
        groups.append(r)
    if len(groups) > len(_KK_SCALE):
        return None  # больше триллиона — пусть читается по цифрам
    parts: list[str] = []
    for idx in range(len(groups) - 1, -1, -1):
        g = groups[idx]
        if not g:
            continue
        if idx == 1 and g == 1:  # 1000 -> «мың» (без «бір»)
            parts.append(_KK_SCALE[idx])
        else:
            parts.extend(_kk_triple(g))
            if idx:
                parts.append(_KK_SCALE[idx])
    res = " ".join(parts)
    return f"минус {res}" if neg else res


def _kk_ordinal(n: int) -> str:
    """Целое -> порядковое (214 -> 'екі жүз он төртінші')."""
    c = _kk_cardinal(n)
    if c is None:
        return str(n)
    words = c.split()
    words[-1] = _KK_ORDINAL_LAST.get(words[-1], words[-1] + "ыншы")
    return " ".join(words)


def _kk_digits(s: str) -> str:
    """Цифры по одной (для ЖСН/БСН, телефонов)."""
    return " ".join("нөл" if d == "0" else _KK_ONES[int(d)] for d in s)


def _kk_num_str(tok: str) -> str:
    had_sep = bool(re.search(r"[\s ]", tok))  # были ли разделители тысяч?
    core = re.sub(r"[\s ]", "", tok)  # убрать разделители тысяч (пробел/nbsp)
    if "," in core:
        intp, frac = core.split(",", 1)
        whole = _kk_cardinal(int(intp or 0))
        place = _KK_FRAC_PLACE.get(len(frac))
        if whole and place:
            return f"{whole} бүтін {place} {_kk_cardinal(int(frac))}"
        return f"{whole or _kk_digits(intp)} бүтін {_kk_digits(frac)}"
    # Длинный код БЕЗ разделителей (ЖСН/БСН, телефон) — по цифрам. А «100 000 000»
    # (с разделителями тысяч) — это сумма, её читаем словами («жүз миллион»).
    if len(core) >= 9 and not had_sep:
        return _kk_digits(core)
    c = _kk_cardinal(int(core))
    return c if c is not None else _kk_digits(core)


def _kk_num_repl(m: "re.Match") -> str:
    try:
        return _kk_num_str(m.group(0))
    except Exception:
        return m.group(0)


def _kk_pct_sub(m: "re.Match") -> str:
    try:
        return f"{_kk_num_str(m.group(1))} пайыз"
    except Exception:
        return m.group(0)


# «N-бап», «5-тармақ», «2024-жыл» -> порядковое (дефис+слово -> «... слово»).
_KK_ORD_HYPHEN_RE = re.compile(rf"\b(\d{{1,4}})-([{_KK_LET}]+)")
# Год через пробел: «2024 жыл/жылы/жылғы» -> порядковое.
_KK_YEAR_RE = re.compile(r"\b(\d{4})\s+(жыл\w*)", re.IGNORECASE)
# Дата: день месяца — порядковое, как в русском («15 наурыз» -> «он бесінші
# наурыз»). Месяц берём с любым падежным окончанием («наурызда», «қаңтардан»).
_KK_MONTHS = ("қаңтар|ақпан|наурыз|сәуір|мамыр|маусым|шілде|тамыз|қыркүйек|"
              "қазан|қараша|желтоқсан")
_KK_DATE_RE = re.compile(rf"\b(\d{{1,2}})\s+({_KK_MONTHS})(\w*)", re.IGNORECASE)
# Сам суффикс порядкового, записанный после дефиса («2-ші»): его НЕ оставляем
# отдельным словом — порядковое числительное уже содержит нужное окончание.
_KK_ORD_SUFFIXES = {"ші", "шы", "ыншы", "інші", "ншы", "нші"}


def _kk_ord_hyphen_sub(m: "re.Match") -> str:
    ordinal = _kk_ordinal(int(m.group(1)))
    word = m.group(2)
    if word.lower() in _KK_ORD_SUFFIXES:
        return ordinal  # «2-ші» -> «екінші» (без дублирующего «ші»)
    return f"{ordinal} {word}"


def _kk_ord_year_sub(m: "re.Match") -> str:
    return f"{_kk_ordinal(int(m.group(1)))} {m.group(2)}"


def _kk_ord_date_sub(m: "re.Match") -> str:
    day = int(m.group(1))
    if not 1 <= day <= 31:          # не дата — оставляем числу общее правило
        return m.group(0)
    return f"{_kk_ordinal(day)} {m.group(2)}{m.group(3)}"


# Телефон казахской фразы: как в русском (_ru_phone_words), но ключевое слово
# «нөмір/телефон» и казахские слова цифр. Телефон СО ПРОБЕЛАМИ/ДЕФИСАМИ
# («8 800 080 18 90») раньше не ловился (были только слитные \d{4,11} рядом со
# словом) и уходил в общий _NUM_RE — 11 цифр читались гигантским количественным
# («жеті миллион…», отзыв 2026-07-21).
def _kk_phone_group(g: str) -> str:
    """Группа цифр телефона: 2–3 цифры без ведущего нуля — количественным, иначе по цифрам."""
    if 2 <= len(g) <= 3 and not g.startswith("0"):
        c = _kk_cardinal(int(g))
        if c is not None:
            return c
    return _kk_digits(g)


def _kk_phone_words(raw: str) -> str:
    """Телефон/код -> казахские слова группами через запятую (запятая = пауза в TTS)."""
    groups = re.findall(r"\d+", raw)
    if len(groups) == 1:  # слитная запись — группируем сами (как _ru_phone_words)
        s = groups[0]
        if len(s) == 11:
            groups = [s[:1], s[1:4], s[4:7], s[7:9], s[9:]]
        elif len(s) == 10:
            groups = [s[:3], s[3:6], s[6:8], s[8:]]
        elif len(s) == 7:
            groups = [s[:3], s[3:5], s[5:]]
    words = ", ".join(_kk_phone_group(g) for g in groups)
    return f"плюс {words}" if raw.lstrip().startswith("+") else words


# Ключевое слово ПЕРЕД цифрами: «нөмір 1458», «телефон 8 800 080 18 90» (до двух
# слов между: «сенім телефоны 1414»). Цифры — слитно \d{4,11} ИЛИ с разделителями.
_KK_PHONE_KW_RE = re.compile(
    r"\b((?:нөмір\w*|телефон\w*)(?:\s+[а-яёәіңғүұқөһ]+){0,2})\s+(\+?\d[\d\s\-()]{2,17}\d|\d{4,11})",
    re.IGNORECASE)
# Цифры ПЕРЕД ключевым словом: «1458 нөміріне», «8 800 ... нөмірі».
_KK_PHONE_KW_RE2 = re.compile(
    r"(\+?\d[\d\s\-()]{2,17}\d|\d{4,11})[\s\-]*(нөмір\w*)", re.IGNORECASE)


def _kk_numbers(text: str) -> str:
    """Цифры -> казахские слова. «N-бап»/годы — ПОРЯДКОВЫЕ, проценты -> пайыз,
    номера телефонов и длинные коды (ЖСН) — по цифрам группами, остальное — количественные."""
    # Телефоны — ДО общего числа: иначе 11 цифр читаются миллиардами. Группами
    # через запятую (пауза), формат телефонов языконезависим — переиспользуем
    # русские regex-ы (_RU_PHONE_BARE_RE/_RU_LONG_CODE_RE) с казахскими словами.
    text = _KK_PHONE_KW_RE.sub(                     # «нөмір/телефон 8 800 ...»
        lambda m: f"{m.group(1)} {_kk_phone_words(m.group(2))}", text)
    text = _KK_PHONE_KW_RE2.sub(                    # «1458 нөміріне»
        lambda m: f"{_kk_phone_words(m.group(1))} {m.group(2)}", text)
    text = _RU_PHONE_BARE_RE.sub(                   # +7/8 ... без слова «нөмір»
        lambda m: _kk_phone_words(m.group(0)), text)
    text = _RU_LONG_CODE_RE.sub(                    # слитные 10+ цифр (сотовый/ЖСН)
        lambda m: _kk_phone_words(m.group(0)), text)
    text = _KK_DATE_RE.sub(_kk_ord_date_sub, text)          # «15 наурыз» -> порядковое
    text = _KK_ORD_HYPHEN_RE.sub(_kk_ord_hyphen_sub, text)  # N-бап -> порядковое
    text = _KK_YEAR_RE.sub(_kk_ord_year_sub, text)          # NNNN жыл -> порядковое
    text = re.sub(r"(\d+(?:,\d+)?)\s*%", _kk_pct_sub, text)  # проценты -> пайыз
    text = _FRAC_RE.sub(_kk_frac_sub, text)                 # 2/3 -> «үштен екі»
    return _NUM_RE.sub(_kk_num_repl, text)                  # остальные -> количественные


# --- Адреса сайтов: egov.kz, afm.gov.kz ------------------------------------
# Точка внутри адреса — НЕ конец предложения, а озвучке она достаётся именно так:
# TTS ставит на ней паузу, как в конце фразы, а нарезка по предложениям может
# разрезать кусок посреди адреса. Поэтому точку убираем, а домен верхнего уровня
# читаем словом. Имя сайта остаётся латиницей — его добьёт транслит следующим
# шагом (egov -> «егов»), либо словарь брендов, если адрес в нём уже есть.
_TLD_WORDS = {"gov.kz": "гов кз", "kz": "кз", "com": "ком",
              "org": "орг", "net": "нет", "ru": "ру"}
_DOMAIN_RE = re.compile(
    r"\b([A-Za-z][A-Za-z0-9-]*)\.(gov\.kz|kz|com|org|net|ru)\b", re.IGNORECASE)


def _domain_sub(m: "re.Match") -> str:
    return f"{m.group(1)} {_TLD_WORDS[m.group(2).lower()]}"


# --- Латиница -> кириллица (фолбэк после словаря брендов) -------------------
# TTS ru/kk латиницу читает криво или молчит. Приближённая англо-транслитерация:
# слова из словаря _NORM_COMMON уже заменены, здесь добиваем всё остальное.
_TRANSLIT_DIGRAPHS = [
    ("tion", "шн"), ("sch", "ш"), ("sh", "ш"), ("ch", "ч"), ("ck", "к"),
    ("ph", "ф"), ("th", "т"), ("qu", "кв"), ("oo", "у"), ("ee", "и"),
    ("ea", "и"), ("ay", "ей"), ("ey", "ей"), ("oy", "ой"), ("ai", "ей"),
    ("ow", "оу"), ("ng", "нг"),
]
_TRANSLIT_ONE = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "кс", "y": "и", "z": "з",
}
_LAT_TOKEN = re.compile(r"[A-Za-z][A-Za-z'’-]*")


def _translit_word(w: str) -> str:
    s = w.lower()
    # немая конечная e (google, store) — не читается
    if len(s) > 3 and s.endswith("e") and s[-2] not in "aeiou":
        s = s[:-1]
    out, i = [], 0
    while i < len(s):
        for dg, rep in _TRANSLIT_DIGRAPHS:
            if s.startswith(dg, i):
                out.append(rep)
                i += len(dg)
                break
        else:
            ch = s[i]
            if ch == "c" and i + 1 < len(s) and s[i + 1] in "eiy":
                out.append("с")           # ce/ci/cy -> с (office, city)
            else:
                out.append(_TRANSLIT_ONE.get(ch, ch))
            i += 1
    return "".join(out)


def _normalize_for_tts(text: str, language: str | None) -> str:
    """Раскрывает аббревиатуры/латиницу/числа в произносимый вид (только для озвучки)."""
    # Домен — ДО словаря брендов: словарь заменяет «e-Gov» на кириллицу, после
    # чего латинский regex адреса уже не сработает и точка уедет в озвучку.
    text = _DOMAIN_RE.sub(_domain_sub, text)  # egov.kz -> «egov кз» (точку убираем)
    for pat, rep in _NORM_COMMON:
        text = re.sub(pat, rep, text, flags=re.IGNORECASE)
    # оставшаяся латиница -> примерная кириллица (словарь выше — приоритетнее)
    text = _LAT_TOKEN.sub(lambda m: _translit_word(m.group(0)), text)
    if _resolve_lang(language) == "kk":
        for pat, rep in _NORM_KK_CHAIN:      # юр-цепочки в родительном падеже
            text = re.sub(pat, rep, text)
    if _resolve_lang(language) == "ru":
        text = _ru_expand_codes(text)  # УК/УПК/КоАП -> полные названия с падежом
        for pat, rep in _NORM_RU:
            text = re.sub(pat, rep, text)
        return _ru_numbers(text)  # числа -> слова (ПОСЛЕ раскрытия аббревиатур)
    # казахский: сперва простые замены, затем склоняемые аббревиатуры
    for pat, rep in _NORM_KK_SIMPLE:
        text = re.sub(pat, rep, text)
    for abbr, expansion, wtype in _NORM_KK_DECL:
        rx = re.compile(rf"\b{abbr}(?:-([а-яёәіңғүұқөһ]+))?\b")
        text = rx.sub(
            lambda m, e=expansion, w=wtype: _kk_inflect(e, w, _kk_case(m.group(1))),
            text,
        )
    return _kk_numbers(text)  # числа -> слова (ПОСЛЕ раскрытия аббревиатур)


# --- Экранные блоки: [ТАБЛИЦА]...[/ТАБЛИЦА] -------------------------------
# RAG может приложить к устному ответу таблицу ДЛЯ ЭКРАНА (правило о таблице в промпте,
# рендерит фронтенд video_ui). Голосу она не нужна: TTS читал бы «палки» и
# цифры кашей. Вырезаем блок и, на всякий случай, бесхозные строки-таблицы
# с «|» без маркеров (LLM иногда забывает маркеры).
_TABLE_BLOCK_RE = re.compile(r"\[(ТАБЛИЦА|КЕСТЕ)\].*?(?:\[/\1\]|\Z)",
                             re.IGNORECASE | re.DOTALL)
_TABLE_LINE_RE = re.compile(r"^[^\n|]*\|[^\n]*$", re.MULTILINE)


def strip_display_blocks(text: str) -> str:
    """Текст без экранных блоков (таблиц) — то, что реально озвучиваем.

    Полный текст (с таблицей) уходит в X-Answer и на экран как есть.
    """
    text = _TABLE_BLOCK_RE.sub(" ", text)
    text = _TABLE_LINE_RE.sub(" ", text)
    return re.sub(r"\n{3,}", "\n\n", text).strip()


# Буквы, которых нет в русском алфавите, — по ним узнаём казахский текст.
# Их доля в живом казахском ~10-15% (одна только «і» встречается в каждом
# втором слове), в русском — ровно ноль.
_KK_ONLY_LETTERS = set("әғқңөұүһі")
# Короткая реплика языка не показывает («Да.», «Иә.») — там доверяем запрошенному.
_LANG_MIN_LETTERS = 6
# Порог доли: одна казахская буква, случайно попавшая в длинный русский ответ
# (название, цитата), не должна переключать движок.
_KK_MIN_SHARE = 0.01


def detect_lang(text: str, fallback: str | None = None) -> str:
    """Язык ТЕКСТА, который будем озвучивать, — 'ru' или 'kk'.

    Нужна потому, что язык ОТВЕТА и язык КИОСКА — разные вещи. Переключатель на
    экране задаёт язык распознавания, а RAG отвечает на языке ВОПРОСА (правило 1
    промпта). Гражданин подошёл к киоску в казахском режиме и спросил
    по-русски — ответ придёт русский, и раньше он уходил в казахский движок:
    русский текст читался казахским голосом, а числа разворачивались казахским
    конвертером. Замечено на киоске 31.07 (бейдж «ҚАЗ», ответ по-русски).

    Судим по тому, что реально ПРОЗВУЧИТ: экранные таблицы отрезаем, иначе
    русская шапка таблицы перетягивала бы казахский ответ на себя.

    Текст без опознавательных знаков (цифры, короткое «да») языка не выдаёт —
    там возвращаем запрошенный: он всё ещё лучшая догадка, чем монетка.
    """
    letters = [c for c in strip_display_blocks(text).lower() if c.isalpha()]
    if len(letters) < _LANG_MIN_LETTERS:
        return _resolve_lang(fallback)
    kk_hits = sum(1 for c in letters if c in _KK_ONLY_LETTERS)
    if kk_hits / len(letters) >= _KK_MIN_SHARE:
        return "kk"
    # Кириллица без единой казахской буквы = русский, и это НЕ то же самое, что
    # «не смогли определить»: именно здесь ловится русский ответ на казахском
    # киоске, ради которого всё и затевалось.
    if sum(1 for c in letters if "а" <= c <= "я" or c == "ё") >= len(letters) / 2:
        return "ru"
    return _resolve_lang(fallback)


def provider_for_text(text: str, language: str | None = None) -> str:
    """Каким движком озвучим ЭТОТ текст (с поправкой на его язык)."""
    return _provider_for(detect_lang(text, language))


# Граница предложения: после .!?… и переноса строки.
_SENT_SPLIT = re.compile(r"(?<=[.!?…])\s+|\n+")

# Кусок «произносим», если в нём есть хотя бы одна буква (кириллица/латиница).
# Куски из одних цифр/знаков TTS не озвучивает: Spark выдаёт 0 токенов и падает.
_HAS_LETTER = re.compile(r"[^\W\d_]", re.UNICODE)


def _has_speech(text: str) -> bool:
    return bool(_HAS_LETTER.search(text))


# Знаки конца клаузы: после них в живой речи и так пауза, поэтому оборвать
# длинное предложение здесь — естественно.
_CLAUSE_BREAK = re.compile(r"[,;:—–]")


def _break_at_clause(chunk: str) -> tuple[str, str]:
    """Делит накопленный кусок по ПОСЛЕДНЕЙ клаузе: (до знака, остаток).

    Знак у самого начала не берём (остаток был бы почти целым куском и всё
    равно поехал бы дальше) — тогда возвращаем кусок как есть.
    """
    best = -1
    for m in _CLAUSE_BREAK.finditer(chunk):
        best = m.end()
    if best > len(chunk) // 2:
        return chunk[:best].strip(), chunk[best:].strip()
    return chunk, ""


# Служебные слова, на которых кусок обрывать НЕЛЬЗЯ. Куски синтезируются порознь,
# и TTS договаривает кусок как законченную реплику: обрыв на союзе даёт «...и»
# с падающей интонацией, паузу шва, и только потом продолжение («Республики
# Казахстан И / статьёй 218...»). Такое слово переносим в следующий кусок — там
# оно и по смыслу. Список — рус. союзы/предлоги + каз. союзы/послелоги; языки
# не пересекаются, поэтому набор общий.
_DANGLING_WORDS = {
    "и", "а", "но", "или", "либо", "да", "же", "ли", "что", "чтобы", "как", "если",
    "когда", "чем", "в", "во", "на", "по", "до", "от", "из", "за", "к", "ко", "с",
    "со", "о", "об", "обо", "у", "для", "при", "про", "над", "под", "перед",
    "между", "через", "без", "кроме", "после", "около", "свыше", "более", "менее",
    "және", "немесе", "мен", "бен", "пен", "үшін", "туралы", "бойынша", "кейін",
    "дейін", "бастап", "арқылы",
}


def _move_dangling(head: str, tail: str) -> tuple[str, str]:
    """Переносит служебные слова с конца куска в начало следующего."""
    words = head.split()
    while len(words) > 1 and words[-1].lower() in _DANGLING_WORDS:
        tail = f"{words.pop()} {tail}".strip()
    return " ".join(words), tail


def _hard_split(sentence: str, max_chars: int) -> list[str]:
    """Слишком длинное предложение режем на куски не длиннее лимита.

    Режем ПО ГРАНИЦЕ КЛАУЗЫ (запятая/тире/двоеточие), а не строго по словам:
    кусок, оборванный посреди фразы, TTS озвучивает как законченную реплику —
    даёт падающую интонацию и комкает хвост на ровном месте. По запятой конец
    куска попадает туда, где пауза уместна, и шов не слышен. Если знаков нет
    (длинное перечисление одними словами) — словесный фолбэк, но и там кусок не
    заканчивается служебным словом (см. _move_dangling).

    Увеличивать max_chars вместо этого нельзя: время синтеза растёт квадратично
    (замер на Spark: 100 симв. -> 18 c, 330 симв. -> 117 c).
    """
    parts: list[str] = []
    cur = ""
    for word in sentence.split():
        if cur and len(cur) + 1 + len(word) > max_chars:
            head, tail = _break_at_clause(cur)
            head, tail = _move_dangling(head, tail)  # не обрывать кусок на союзе
            parts.append(head)
            cur = f"{tail} {word}".strip() if tail else word
        else:
            cur = f"{cur} {word}" if cur else word
    if cur:
        parts.append(cur)
    return parts


def _split_for_tts(text: str, sentence_max: int, group_max: int) -> list[str]:
    """Готовит текст к синтезу, минимизируя число склеиваемых кусков.

    F5 сам делит текст на предложения, но обрезает ОДНО предложение длиннее
    ~182 симв. (ru). Поэтому: слишком длинное предложение режем по словам
    (<= sentence_max), а целые предложения группируем в крупные куски
    (<= group_max) — F5 озвучит такой кусок слитно, с естественными паузами,
    без швов поштучной склейки. При group_max == sentence_max поведение
    прежнее (мелкие куски) — для TTS без собственной нарезки (spark).
    """
    text = text.strip()
    # 1) нормализуем предложения: слишком длинные дробим по словам
    sentences: list[str] = []
    for sent in _SENT_SPLIT.split(text):
        sent = sent.strip()
        if not sent:
            continue
        if len(sent) > sentence_max:
            sentences.extend(_hard_split(sent, sentence_max))
        else:
            sentences.append(sent)
    if not sentences:
        return [text]
    # 2) группируем предложения в куски не длиннее group_max
    chunks: list[str] = []
    cur = ""
    for sent in sentences:
        if cur and len(cur) + 1 + len(sent) > group_max:
            chunks.append(cur)
            cur = sent
        else:
            cur = f"{cur} {sent}" if cur else sent
    if cur:
        chunks.append(cur)
    return chunks


def _gap_ms_after(text: str, base_ms: int) -> int:
    """Сколько тишины вставить ПОСЛЕ куска — по тому, чем он закончился.

    Куски синтезируются порознь, и TTS подрезает собственный хвост тишины: без
    зазора следующий кусок «влезает», не дав предыдущему договорить. Но пауза
    нужна разная: после точки — как между фразами, после запятой — вдвое короче
    (там середина предложения, полная пауза рвала бы его надвое).
    `base_ms` — полная пауза провайдера (у F5 длиннее, см. tts_f5_gap_ms).
    """
    end = text.rstrip()[-1:]
    if end in ".!?":
        return base_ms
    return base_ms // 2


def _concat_wav(parts: list[bytes], texts: list[str] | None = None,
                gap_ms: int | None = None) -> bytes:
    """Склеивает несколько WAV-блоков в один, вставляя паузу между кусками.

    `texts` — исходные тексты кусков (той же длины, что `parts`): по ним пауза
    подбирается под знак на стыке. Без них — одинаковый зазор, как раньше.
    `gap_ms` — полная пауза (по умолчанию tts_gap_ms).
    """
    if len(parts) == 1:
        return parts[0]
    base_ms = settings.tts_gap_ms if gap_ms is None else gap_ms
    out = io.BytesIO()
    writer: wave.Wave_write | None = None

    fmt: tuple[int, int, int] | None = None  # (nchannels, sampwidth, framerate) первого куска
    try:
        for idx, blob in enumerate(parts):
            with wave.open(io.BytesIO(blob), "rb") as reader:
                params = (reader.getnchannels(), reader.getsampwidth(),
                          reader.getframerate())
                if writer is None:
                    fmt = params
                    nch, sw, fr = params
                    writer = wave.open(out, "wb")
                    writer.setnchannels(nch)
                    writer.setsampwidth(sw)
                    writer.setframerate(fr)
                elif params != fmt:
                    # Куски с разной частотой/каналами склеивать нельзя — иначе
                    # получится ускоренный/искажённый звук БЕЗ ошибки. Падаем явно.
                    raise RuntimeError(
                        f"Несовместимые параметры WAV при склейке: {params} != {fmt}"
                    )
                if idx:  # пауза перед каждым, кроме первого — по знаку на стыке
                    ms = _gap_ms_after(texts[idx - 1], base_ms) if texts else base_ms
                    nch, sw, fr = fmt
                    n_frames = int(fr * ms / 1000)
                    writer.writeframes(b"\x00" * (n_frames * nch * sw))
                writer.writeframes(reader.readframes(reader.getnframes()))
    finally:
        if writer is not None:
            writer.close()
    return out.getvalue()


def prepare_for_tts(text: str, language: str | None = None,
                    provider: str | None = None) -> tuple[str, list[str]]:
    """Что реально уйдёт в TTS: (текст для озвучки, куски для синтеза).

    `provider` — явный движок (у фолбэка свои лимиты куска: eleven держит 800
    символов, Spark 260, F5 группирует по 240); по умолчанию — движок языка.

    Вынесено из synthesize() отдельной функцией, чтобы бенч
    (`python -m scripts.tts_bench`) показывал РОВНО ту нарезку и нормализацию,
    что идут в бой, а не их копию, которая со временем разъедется.
    """
    # Язык берём ИЗ ТЕКСТА, а не из переключателя киоска (см. detect_lang).
    language = detect_lang(text, language)
    # Экранные таблицы не озвучиваем (их рендерит фронтенд). Если ответ состоял
    # из одной таблицы — киоск не должен получить 5xx: озвучиваем отсылку к экрану.
    speech = strip_display_blocks(text)
    if not _has_speech(speech):
        speech = ("Жауап экранда көрсетілген."
                  if _resolve_lang(language) == "kk"
                  else "Ответ показан на экране.")
    # Раскрываем аббревиатуры/латиницу в произносимый вид (только для звука).
    speech = _normalize_for_tts(speech, language)
    # F5 сам делит текст на предложения — отдаём крупные куски (меньше швов).
    # Spark своей нарезки не имеет: режем сами, но его предел (3000) куда выше
    # F5-шных 180, поэтому даём предложению запас — чтобы разрез попал на запятую,
    # а не в середину фразы (иначе Spark комкает хвост огрызка).
    provider = provider or _provider_for(language)
    if provider == "eleven":
        # eleven держит длинный текст сам — крупные куски, минимум швов.
        #
        # ⚠️ Предложение НЕ РЕЖЕМ на границе лимита. eleven_v3 генерирует
        # интонацию заново на каждый запрос, поэтому между кусками тембр и темп
        # плывут. Если стык попал внутрь фразы, скачок слышен как чужой голос
        # посреди слова (замечено на киоске 30.07); на границе предложения его
        # маскирует естественная пауза. Раньше здесь стояло
        # sent_max = ELEVENLABS_MAX_CHARS (на бою 200), и любое юридическое
        # предложение длиннее 200 символов — то есть обычное — рвалось по
        # запятой. Теперь дробим только патологию: строку без точек длиннее
        # ELEVENLABS_SENTENCE_CAP (например, слипшееся перечисление из RAG).
        #
        # Плата: одно длинное предложение = один длинный кусок, первый звук
        # приходит позже. Для облака это линейно по длине (в отличие от Spark с
        # его квадратичным ростом), поэтому обмен выгодный: ровный голос важнее
        # секунды ожидания.
        sent_max = max(settings.elevenlabs_max_chars,
                       settings.elevenlabs_sentence_cap)
        group = settings.elevenlabs_max_chars
    elif provider == "omni":
        # Предложение НЕ РЕЖЕМ на границе лимита — как у eleven. Шов внутри фразы
        # слышен как запинка: интонация начинается заново, да ещё и с паузой
        # склейки (400/250 мс), а юридическое предложение на 330+ символов —
        # норма для кодексов. Дробим только патологию: строку без точек длиннее
        # cap. Куски под поток задаёт group.
        sent_max = max(settings.tts_kk_sentence_cap, settings.tts_kk_group_chars)
        group = settings.tts_kk_group_chars
    elif provider == "spark":
        # Spark своей нарезки не имеет и растёт квадратично по длине, поэтому у
        # него ПРЕЖНИЙ, более мелкий лимит: запас ровно чтобы разрез дотянулся до
        # запятой. Движок снят с боя, но настройку не трогаем — вернут, и она
        # должна работать как раньше.
        sent_max = group = max(settings.tts_max_chars, settings.tts_kk_max_chars)
    else:
        sent_max = settings.tts_max_chars
        group = settings.tts_group_chars if provider == "f5" else settings.tts_max_chars
    # Выкидываем куски без букв (одни цифры/знаки) — TTS на них падает.
    parts = [p for p in _split_for_tts(speech, sent_max, group) if _has_speech(p)]
    return speech, parts


async def _synthesize_all(text: str, language: str | None, provider: str,
                          fail_fast: bool = False) -> bytes:
    """Весь ответ одним провайдером: нарезка -> синтез кусков -> склейка.

    `fail_fast` — есть страховка (фолбэк), поэтому ПЕРВЫЙ кусок синтезируем без
    повторов: если движок лежит (облако недоступно), повтор только удваивает
    ожидание у киоска, а запасной движок ответит быстрее. Дальше повторы
    остаются: там сбой означал бы пересинтез всего ответа заново.
    """
    speech, parts = prepare_for_tts(text, language, provider)
    head_retries = 0 if fail_fast else None
    # Склейка реализована для WAV; для иных форматов синтезируем одним куском.
    if settings.tts_format != "wav":
        return await _synthesize_chunk(speech, language, provider, head_retries)
    if not parts:
        raise RuntimeError("Нет произносимого текста для синтеза")
    if len(parts) == 1:
        result = await _synthesize_chunk(parts[0], language, provider, head_retries)
    else:
        audios = [await _synthesize_chunk(part, language, provider,
                                          head_retries if idx == 0 else None)
                  for idx, part in enumerate(parts)]
        gap = settings.tts_f5_gap_ms if provider == "f5" else settings.tts_gap_ms
        result = _concat_wav(audios, parts, gap)
    # Шумовой хвост F5 в самом конце ответа плавно гасим в ноль (см. _F5_TAIL_FADE_MS).
    if provider == "f5" and settings.tts_format == "wav":
        result = _fade_out_tail(result, _F5_TAIL_FADE_MS)
    return result


async def synthesize_with_provider(text: str, language: str | None = None
                                   ) -> tuple[bytes, str]:
    """Текст -> (аудио, ПРОВАЙДЕР, которым в итоге озвучили).

    Провайдер важен вызывающему: киоск по нему выбирает темп проигрывания
    (Spark медленный — ускоряем плеером), и после фолбэка это уже не тот
    провайдер, что настроен для языка.
    """
    if not text.strip():
        raise RuntimeError("Пустой текст для синтеза")
    language = detect_lang(text, language)
    primary = _provider_for(language)
    fallback = _fallback_for(language)
    # Провайдер, отказавший только что, пропускаем без попытки: иначе каждый
    # запрос в офлайн-сети платит полный таймаут облака (см. tts_fallback_cooldown).
    if fallback and _in_cooldown(primary):
        log.warning("TTS %s пропущен (недавний отказ), сразу фолбэк %s", primary, fallback)
        return await _synthesize_all(text, language, fallback), fallback
    try:
        result = await _synthesize_all(text, language, primary, fail_fast=bool(fallback))
    except Exception as e:
        if not fallback:
            raise
        _mark_down(primary)
        log.warning("TTS %s не смог (%r) -> фолбэк %s", primary, e, fallback)
        return await _synthesize_all(text, language, fallback), fallback
    _mark_up(primary)
    return result, primary


async def synthesize(text: str, language: str | None = None) -> bytes:
    """Текст -> аудио (WAV-байты). Длинный текст режется и склеивается."""
    audio, _ = await synthesize_with_provider(text, language)
    return audio


def _append_silence(wav_bytes: bytes, ms: int) -> bytes:
    """Дописывает `ms` тишины в конец WAV (не WAV — отдаём как есть).

    В монолитном пути паузу на стыке ставит склейка (_concat_wav). В потоковом
    куски играются порознь, склейки нет — значит паузу нужно вшить в хвост
    куска, иначе следующий начнётся впритык и «влезет», не дав предыдущему
    договорить (та самая настройка 280/140 и 300/150, подобранная на слух).
    """
    if ms <= 0:
        return wav_bytes
    try:
        with wave.open(io.BytesIO(wav_bytes), "rb") as r:
            nch, sw, fr = r.getnchannels(), r.getsampwidth(), r.getframerate()
            frames = r.readframes(r.getnframes())
    except (wave.Error, EOFError):
        return wav_bytes
    out = io.BytesIO()
    with wave.open(out, "wb") as w:
        w.setnchannels(nch)
        w.setsampwidth(sw)
        w.setframerate(fr)
        w.writeframes(frames + b"\x00" * (int(fr * ms / 1000) * nch * sw))
    return out.getvalue()


async def synthesize_stream(text: str, language: str | None = None):
    """Куски озвучки ПО МЕРЕ синтеза: (номер, WAV, провайдер, символов в куске).

    Ради этого и делался стриминг: гражданин слышит первый кусок, пока
    досинтезируются остальные. Синтез идёт быстрее реального времени (F5 на GPU
    АФМ — примерно в 8 раз), поэтому очередь не пустеет, а ожидание падает с
    полного времени ответа до времени ОДНОГО первого куска.

    Паузы на стыках вшиты в хвост куска (см. _append_silence), гашение хвоста
    F5 — в последний кусок: звучать должно ровно как склеенный WAV.

    Фолбэк на запасной движок возможен ТОЛЬКО до первого выданного куска: менять
    голос на середине ответа хуже, чем честно оборвать (гражданин уже слышит
    начало, а текст целиком на экране с самого начала).
    """
    if not text.strip():
        raise RuntimeError("Пустой текст для синтеза")
    language = detect_lang(text, language)
    primary = _provider_for(language)
    fallback = _fallback_for(language)
    provider = fallback if (fallback and _in_cooldown(primary)) else primary
    if provider != primary:
        log.warning("TTS %s пропущен (недавний отказ), сразу фолбэк %s", primary, provider)

    # Первый кусок синтезируем ДО выдачи: только пока ничего не отдано, отказ
    # ещё можно молча пережить сменой движка.
    while True:
        speech, parts = prepare_for_tts(text, language, provider)
        # Паузы на стыке и гашение хвоста умеем только для WAV, поэтому иной
        # формат отдаём одним куском — ровно как монолитный путь (стриминга там
        # не будет, зато звучание не разъедется с /voice).
        if settings.tts_format != "wav":
            parts = [speech]
        if not parts:
            raise RuntimeError("Нет произносимого текста для синтеза")
        try:
            # Есть страховка -> первый кусок без повторов: лежачее облако не
            # должно удваивать ожидание перед уходом на офлайн-движок.
            head = await _synthesize_chunk(
                parts[0], language, provider,
                0 if (fallback and provider == primary) else None)
            break
        except Exception as e:
            if provider != primary or not fallback:
                raise
            _mark_down(primary)
            log.warning("TTS %s не смог (%r) -> фолбэк %s", primary, e, fallback)
            provider = fallback
    if provider == primary:
        _mark_up(primary)

    base_gap = settings.tts_f5_gap_ms if provider == "f5" else settings.tts_gap_ms
    for idx, part in enumerate(parts):
        audio = head if idx == 0 else await _synthesize_chunk(part, language, provider)
        if idx < len(parts) - 1:
            audio = _append_silence(audio, _gap_ms_after(part, base_gap))
        elif provider == "f5" and settings.tts_format == "wav":
            audio = _fade_out_tail(audio, _F5_TAIL_FADE_MS)
        yield idx, audio, provider, len(part)


def _provider_for(language: str | None) -> str:
    """Какой TTS-провайдер обслуживает данный язык (kk -> свой провайдер)."""
    return settings.tts_kk_provider if _resolve_lang(language) == "kk" else settings.tts_provider


def _fallback_for(language: str | None) -> str:
    """Запасной провайдер языка (пусто — фолбэка нет). Сам себе не фолбэк."""
    fb = (settings.tts_kk_fallback if _resolve_lang(language) == "kk"
          else settings.tts_fallback).strip()
    return fb if fb and fb != _provider_for(language) else ""


# Провайдер -> момент последнего отказа (monotonic). Предохранитель: пока идёт
# кулдаун, провайдер не дёргаем вовсе — см. synthesize_with_provider.
_provider_down: dict[str, float] = {}


def _in_cooldown(provider: str) -> bool:
    failed_at = _provider_down.get(provider)
    if failed_at is None:
        return False
    if time.monotonic() - failed_at < settings.tts_fallback_cooldown:
        return True
    del _provider_down[provider]      # кулдаун истёк — можно пробовать снова
    return False


def _mark_down(provider: str) -> None:
    _provider_down[provider] = time.monotonic()


def _mark_up(provider: str) -> None:
    _provider_down.pop(provider, None)


async def _synthesize_chunk(text: str, language: str | None, provider: str,
                            retries: int | None = None) -> bytes:
    """Синтез куска с повторами: единичный сетевой сбой не рушит весь ответ.

    Повторяем ТОЛЬКО то, что может пройти со второй попытки (сеть, 5xx, битый
    ответ). Наши собственные RuntimeError — это «провайдер не настроен»: их
    повтор не вылечит, отдаём сразу (и выше сработает фолбэк).
    `retries` — сколько повторов (None = tts_retries из настроек; 0 — когда
    наверху есть фолбэк и ждать второй попытки дороже, чем сменить движок).
    """
    limit = settings.tts_retries if retries is None else retries
    last: Exception | None = None
    for attempt in range(limit + 1):
        try:
            return await _synthesize_one(text, language, provider)
        except RuntimeError:
            raise
        except Exception as e:
            last = e
            if attempt < limit:
                log.warning("TTS %s: кусок не синтезировался (%r), повтор %d",
                            provider, e, attempt + 1)
                await asyncio.sleep(0.5 * (attempt + 1))
    raise last  # type: ignore[misc]


async def _synthesize_one(text: str, language: str | None = None,
                          provider: str | None = None) -> bytes:
    """Синтез одного фрагмента. Провайдер — явный либо по языку."""
    provider = provider or _provider_for(language)
    if provider == "say":
        return await _say(text, language)
    if provider == "openai":
        return await _openai(text)
    if provider == "f5":
        return await _f5(text, language)
    if provider == "spark":
        return await _spark(text, language)
    if provider == "omni":
        return await _omni(text, language)
    if provider == "eleven":
        return await _eleven(text, language)
    raise RuntimeError(f"Неизвестный TTS-провайдер: {provider!r}")


# ---------- macOS say (только локальная отладка) ----------
async def _say(text: str, language: str | None) -> bytes:
    # У macOS нет казахского голоса — для kk звучание будет неточным (это ок для отладки).
    voice = "Milena"  # русский голос
    with tempfile.TemporaryDirectory() as d:
        aiff = os.path.join(d, "out.aiff")
        wav = os.path.join(d, "out.wav")
        p1 = await asyncio.create_subprocess_exec(
            "say", "-v", voice, "-o", aiff, text,
            stderr=asyncio.subprocess.PIPE,
        )
        _, err = await p1.communicate()
        if p1.returncode != 0:
            raise RuntimeError(f"say error: {err.decode(errors='ignore')}")
        p2 = await asyncio.create_subprocess_exec(
            "afconvert", aiff, "-f", "WAVE", "-d", "LEI16@22050", "-c", "1", wav,
            stderr=asyncio.subprocess.PIPE,
        )
        _, err = await p2.communicate()
        if p2.returncode != 0:
            raise RuntimeError(f"afconvert error: {err.decode(errors='ignore')}")
        with open(wav, "rb") as f:
            return f.read()


# ---------- F5-TTS_RUSSIAN (русский, отдельный сервис по HTTP) ----------
# Тишина по краям куска у F5 ГУЛЯЕТ (замер 2026-07-17: голова 41–157 мс, хвост
# 45–165 мс). Из-за этого пауза на стыке кусков плавала от 0.5 до 0.7 c (наш
# зазор + случайные края), а кусок с короткой головой звучал «не с начала».
# Нормализуем: подрезаем тишину по краям до _EDGE_KEEP_MS — стык становится
# ровно TTS_F5_GAP_MS (+2×_EDGE_KEEP_MS), одинаковый на каждом шве.
# 45 (было 30): при 30 F5 изредка «съедал» тихий край слова (спад/атака ниже
# _ONSET_THRESH) на стыке кусков — конец куска и начало следующего звучали
# недоговорённо. Больше края оставляем — слово договаривается. Если всё ещё
# режется, второй рычаг — снизить _ONSET_THRESH (ловит более тихую атаку/спад
# ДО добавления этого запаса). Тюнить на слух.
_EDGE_KEEP_MS = 45
_EDGE_THRESH = 300  # |int16| ниже — считаем тишиной (тот же порог, что в замерах)
# «Хвост-сирота»: короткий всплеск в САМОМ конце, оторванный от речи заметной
# тишиной, — галлюцинация модели в бюджете паддинга («страшный звук» с демо).
# Живая речь куска — один сплошной сегмент (паузы внутри < _BLOB_JOIN_MS);
# замер 2026-07-17: артефакт 270–360 мс через >=200 мс тишины, 2 куска из 9.
_BLOB_JOIN_MS = 180    # тишина короче — внутри речи, сегменты склеиваются
_BLOB_GAP_MS = 180     # всплеск оторван от речи такой тишиной -> кандидат.
                       # РОВНО как join: было 200, и артефакт с отрывом 180–200 мс
                       # проскакивал в слепую зону (сегменты уже раздельные, но
                       # «не оторван»). Замер: артефакты отрываются на 180–230 мс,
                       # естественные паузы внутри речи — до ~190 мс; граница
                       # тонкая, поэтому вдобавок blob<=500 мс и >=1.5 c речи.
# Мягкий разгон звука: атака глухой согласной (С/Ш/Ф) тише порога 300 — границу
# первого/последнего сегмента расширяем, пока амплитуда >= этого порога, иначе
# трим срезал начало слова («съедено начало куска», отзыв 2026-07-17).
_ONSET_THRESH = 80
_BLOB_MAX_MS = 500     # длиннее — это речь, не трогаем
_BLOB_MIN_SPEECH_MS = 1500  # режем хвост только у куска с полноценной речью
# F5 изредка оставляет короткий шумовой «хвост» в самом конце ответа (после
# последней фонемы, в бюджете немого паддинга _f5, который трим убирает не всегда).
# Линейно гасим последние _F5_TAIL_FADE_MS мс всего ответа в ноль: артефакт
# затухает, на речь не влияет (гаснет только край). Тюнить на слух.
_F5_TAIL_FADE_MS = 40


def _trim_edge_silence(wav_bytes: bytes) -> bytes:
    """Ровняет тишину по краям WAV до _EDGE_KEEP_MS и режет «хвосты-сироты».

    Не 16-битный или вовсе не WAV (сервер прислал что-то иное) — отдаём как есть:
    подрезка — украшение, ронять из-за неё синтез нельзя.
    """
    try:
        with wave.open(io.BytesIO(wav_bytes), "rb") as r:
            nch, sw, fr = r.getnchannels(), r.getsampwidth(), r.getframerate()
            frames = r.readframes(r.getnframes())
    except (wave.Error, EOFError):
        return wav_bytes
    if sw != 2 or not frames:
        return wav_bytes
    import array
    samples = array.array("h")
    samples.frombytes(frames)
    step = nch  # рамка = nch сэмплов; громкая — когда громкий ЛЮБОЙ канал
    n = len(samples) // step
    # сегменты речи (паузы короче _BLOB_JOIN_MS склеиваются в один сегмент)
    join = int(fr * _BLOB_JOIN_MS / 1000)
    segs: list[tuple[int, int]] = []
    start = last_loud = None
    for i in range(n):
        loud = any(abs(samples[i * step + c]) >= _EDGE_THRESH for c in range(step))
        if loud:
            if start is None:
                start = i
            last_loud = i
        elif start is not None and i - last_loud > join:
            segs.append((start, last_loud))
            start = None
    if start is not None:
        segs.append((start, last_loud))
    if not segs:
        return wav_bytes
    # отрезаем хвосты-сироты (может быть и не один)
    while len(segs) > 1:
        bs, be = segs[-1]
        blob_ms = (be - bs) / fr * 1000
        gap_ms = (bs - segs[-2][1]) / fr * 1000
        speech_ms = sum(e - s for s, e in segs[:-1]) / fr * 1000
        if (blob_ms <= _BLOB_MAX_MS and gap_ms >= _BLOB_GAP_MS
                and speech_ms >= _BLOB_MIN_SPEECH_MS):
            segs.pop()
        else:
            break
    # мягкий разгон/затухание: расширяем края, пока звук громче _ONSET_THRESH
    def frame_loud(i: int, th: int) -> bool:
        return any(abs(samples[i * step + c]) >= th for c in range(step))
    first, last = segs[0][0], segs[-1][1]
    while first > 0 and frame_loud(first - 1, _ONSET_THRESH):
        first -= 1
    while last < n - 1 and frame_loud(last + 1, _ONSET_THRESH):
        last += 1
    keep = int(fr * _EDGE_KEEP_MS / 1000)
    first = max(0, first - keep)
    last = min(n - 1, last + keep)
    out = io.BytesIO()
    with wave.open(out, "wb") as w:
        w.setnchannels(nch)
        w.setsampwidth(sw)
        w.setframerate(fr)
        w.writeframes(samples[first * step:(last + 1) * step].tobytes())
    return out.getvalue()


def _fade_out_tail(wav_bytes: bytes, ms: int) -> bytes:
    """Линейно гасит последние `ms` мс WAV до нуля (убирает шум/щелчок в конце).

    Не 16-битный или не WAV — отдаём как есть (гашение — украшение, ронять из-за
    него синтез нельзя).
    """
    if ms <= 0:
        return wav_bytes
    try:
        with wave.open(io.BytesIO(wav_bytes), "rb") as r:
            nch, sw, fr = r.getnchannels(), r.getsampwidth(), r.getframerate()
            frames = r.readframes(r.getnframes())
    except (wave.Error, EOFError):
        return wav_bytes
    if sw != 2 or not frames:
        return wav_bytes
    import array
    samples = array.array("h")
    samples.frombytes(frames)
    total = len(samples) // nch
    fade = min(total, int(fr * ms / 1000))
    if fade <= 0:
        return wav_bytes
    start = total - fade
    for i in range(fade):
        g = (fade - 1 - i) / fade  # 1.0 -> 0.0
        for c in range(nch):
            idx = (start + i) * nch + c
            samples[idx] = int(samples[idx] * g)
    out = io.BytesIO()
    with wave.open(out, "wb") as w:
        w.setnchannels(nch)
        w.setsampwidth(sw)
        w.setframerate(fr)
        w.writeframes(samples.tobytes())
    return out.getvalue()
_f5_ref_cache: dict[str, tuple[bytes, str]] = {}  # путь -> (аудио-байты, ref_text)


def _f5_reference() -> tuple[bytes, str]:
    """Клиентский референс (аудио + транскрипт) для multipart-контракта F5.

    Кэшируем в памяти: WAV читается с диска один раз, а не на каждый кусок ответа.
    ref_text вида "@путь" читается из файла (удобно ссылаться на refs/ref_ru.txt).
    """
    path = settings.f5_ref_audio
    cached = _f5_ref_cache.get(path)
    if cached is not None:
        return cached
    if not os.path.isfile(path):
        raise RuntimeError(f"F5_REF_AUDIO={path!r} — файл референса не найден.")
    with open(path, "rb") as f:
        audio = f.read()
    ref_text = settings.f5_ref_text
    if ref_text.startswith("@"):
        ref_path = ref_text[1:]
        if not os.path.isfile(ref_path):
            raise RuntimeError(f"F5_REF_TEXT=@{ref_path} — файл транскрипта не найден.")
        with open(ref_path, encoding="utf-8") as f:
            ref_text = f.read().strip()
    if not ref_text.strip():
        raise RuntimeError(
            "F5_REF_TEXT пуст — multipart-сервер F5 требует транскрипт референса "
            "(укажи текст или @refs/ref_ru.txt в .env)."
        )
    result = (audio, ref_text)
    _f5_ref_cache[path] = result
    return result


async def _f5(text: str, language: str | None) -> bytes:
    """Вызывает F5-TTS-сервер (русский TTS). Два контракта:

    - multipart (если задан F5_REF_AUDIO): POST {ref_audio, ref_text, gen_text}
      — GPU-сервер АФМ, референс шлёт клиент;
    - JSON (иначе): POST {text, language} — локальный f5_server с серверным референсом.
    """
    import httpx
    if not settings.f5_url:
        raise RuntimeError(
            "TTS=f5, но F5_URL не задан. Запусти f5_server и укажи адрес в .env."
        )
    async with httpx.AsyncClient(timeout=180) as client:
        if settings.f5_ref_audio:
            audio, ref_text = _f5_reference()
            # Прогноз длительности у multipart-F5 детерминирован по длине текста
            # и ВПРИТЫК: звук кончается прямо на последней фонеме (хвост тишины
            # 0.00 с), конец слова порой срезан, а темп спешит (~18.5 симв/с) —
            # слова изредка «глотаются» («звонок бесплатны_», «либо подать» →
            # «попадать»). Немые точки в конце gen_text удлиняют прогноз
            # (~0.03 с/символ), САМИ НЕ ОЗВУЧИВАЮТСЯ — модель говорит спокойнее
            # и договаривает. Замер 2026-07-17 (F5 АФМ + STT АФМ).
            # ПОТОЛОК 10 точек ОБЯЗАТЕЛЕН: без него на длинном куске (577 симв.
            # -> 48 точек -> +2.6 c бюджета) модель ЗАПОЛНЯЛА лишнее время
            # «страшным» бормотанием в хвосте (замерено по RMS). Малый запас
            # (+0.5 c) она отдаёт тишиной, большой — галлюцинирует звуком.
            pad = " " + ". " * max(4, min(10, len(text) // 12))
            resp = await client.post(
                settings.f5_url,
                files={"ref_audio": ("ref.wav", audio, "audio/wav")},
                data={"ref_text": ref_text, "gen_text": text + pad},
            )
        else:
            resp = await client.post(
                settings.f5_url,
                json={"text": text, "language": language or "russian"},
            )
        resp.raise_for_status()
        # Ровняем гуляющие края (только там, где склеиваем WAV сами).
        if settings.tts_format == "wav":
            return _trim_edge_silence(resp.content)
        return resp.content


