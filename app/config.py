    def _provider_configured(self, provider: str) -> bool:
        if provider == "openai":
            return bool(self.tts_base_url and self.tts_model)
        if provider == "eleven":
            return bool(self.elevenlabs_api_key and self.elevenlabs_voice_id)
        # f5/spark/omni — сетевые сервисы: без адреса синтез невозможен. Проверяем URL,
        # иначе /health рапортует "включён", а /voice падает 502 уже у гражданина
        # (N3). "say" — локальный (macOS), URL не нужен.
        if provider == "f5":
            return bool(self.f5_url)
        if provider == "spark":
            return bool(self.spark_url)
        if provider == "omni":
            return bool(self.omni_url)
        if provider == "say":
            return True
        return False

    @property
    def tts_enabled(self) -> bool:
        # Оба языковых провайдера (ru: tts_provider, kk: tts_kk_provider) должны
        # быть валидны — иначе /voice может молча остаться без звука для одного
        # из языков, а settings.tts_enabled это не поймает.
        return self._provider_configured(self.tts_provider) and self._provider_configured(
            self.tts_kk_provider
        )


