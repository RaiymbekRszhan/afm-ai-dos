_FALLBACK = ("нет точной информации", "нақты ақпарат жоқ")
# Утечку русского в казахский ответ по БУКВАМ не поймать: казахский алфавит — те же
# кириллические буквы плюс әғқңөұүһі, а «ы/ъ/э/щ» в казахском legit (қылмыстық,
# арқылы). «Русских-эксклюзивных» букв нет. Поэтому эвристика по СЛОВАМ: небольшой
# список частых русских слов, которых не должно быть в казахском ответе. Ловит
# реальные утечки («обращайтесь», «горячей»), не крича на казахское «ы».
_RU_LEAK_WORDS = frozenset("""
если который которая которое которых также поэтому потому обращайтесь обратитесь
горячей горячая горячую вправе однако поскольку значит вместе является нужно
можно каждый очень чтобы через после этого который поскольку течение случае
""".split())


def ru_leak_words(answer: str) -> list[str]:
    return [t for t in re.findall(r"[а-яёА-ЯЁ]{3,}", answer or "")
            if t.lower() in _RU_LEAK_WORDS]
# Метки статей в sources: «..., статья 214» (ru) и «..., 214-бап» (kk).
_RU_ART = re.compile(r",\s*статья\s+(\d+(?:-\d+)?)")
_KK_ART = re.compile(r"(\d+(?:-\d+)?)-бап")


def _has_fallback(answer: str) -> bool:
    return any(m in answer for m in _FALLBACK)


def verdict(exp, answer: str, sources: str) -> str:
    # Запрос не дошёл (сервис не поднят и т.п.) — это НЕ промах поиска. Отдельный
    # вердикт, иначе «пустой ответ» маскируется под MISS и «0 кросс-язык дублей»,
    # создавая ложную картину успеха при погашенном сервисе.
    if (answer or "").startswith("__ERR__"):
        return "ERR"
    a = (answer or "").lower()
    both = a + " " + (sources or "").lower()
    if exp == "FALLBACK":
        return "FB-OK" if _has_fallback(a) else "FB-MISS"
    if _has_fallback(a):
        return "unexpFB"
    return "HIT" if any(x.lower() in both for x in exp) else "MISS"


def crosslang_dupes(sources: str) -> int:
    """Сколько статей пришли ОБЕИМИ версиями (ru «статья N» И kk «N-бап»)."""
    ru = set(_RU_ART.findall(sources or ""))
    kk = set(_KK_ART.findall(sources or ""))
    return len(ru & kk)


async def ask(client: httpx.AsyncClient, url: str, q: str, lang: str) -> dict:
    r = await client.post(url, json={"question": q, "lang": lang, "with_sources": True})
    r.raise_for_status()
    return r.json()


async def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:8077/ask")
    ap.add_argument("--json", default=None, help="куда выгрузить сырьё (для A/B diff)")
    args = ap.parse_args(argv)

    rows, dump = [], []
    sem = asyncio.Semaphore(4)  # не топим медленный LLM АФМ (LLM_MAX_ASYNC=4)
    async with httpx.AsyncClient(timeout=180) as client:
        async def run(p):
            pid, cat, q, lang, exp = p
            async with sem:
                try:
                    d = await ask(client, args.url, q, lang)
                except Exception as e:
                    return pid, cat, q, lang, exp, f"__ERR__ {e}", ""
                return pid, cat, q, lang, exp, d.get("answer", ""), d.get("sources", "")
        rows = await asyncio.gather(*(run(p) for p in PROBES))

    rows = sorted(rows, key=lambda x: (x[1], x[0]))
    cats: Counter = Counter()
    dupes = 0
    leaks: list[str] = []
    for pid, cat, q, lang, exp, answer, sources in rows:
        v = verdict(exp, answer, sources)
        cats[v] += 1
        dupes += crosslang_dupes(sources)
        leaked = ru_leak_words(answer) if lang == "kk" and not _has_fallback(answer) else []
        if leaked:
            leaks.append(f"{pid}:{','.join(sorted(set(leaked)))}")
        print(f"[{v:>7}] {pid} <{cat}/{lang}>{'  ⚠ru:' + ','.join(sorted(set(leaked))) if leaked else ''} {q}")
        print(f"         SRC: {(sources or '')[:320]}")
        print(f"         ANS: {' '.join((answer or '').split())[:220]}")
        dump.append({"id": pid, "cat": cat, "q": q, "lang": lang, "exp": exp,
                     "verdict": v, "dupes": crosslang_dupes(sources),
                     "answer": answer, "sources": sources})

    print("\n=== СВОДКА ===")
    errs = cats.get("ERR", 0)
    if errs:
        print(f"⚠ ВНИМАНИЕ: {errs}/{len(rows)} запросов НЕ ДОШЛИ до сервиса "
              f"(поднят ли :8077? верен ли --url?).")
        print("  Метрики ниже НЕДОСТОВЕРНЫ: «0 дублей» здесь не успех дедупа, а "
              "следствие пустых ответов.")
    print("verdict:", dict(cats))
    print(f"кросс-язык дублей (ru+kk одной статьи в выдаче): {dupes}  — меньше лучше (двигает LANG_DEDUP/реранк)")
    print(f"подозрение на ru-слова в kk-ответе (эвристика по списку): {len(leaks)} {leaks}  — должно быть 0")
    if args.json:
        json.dump(dump, open(args.json, "w"), ensure_ascii=False, indent=1)
        print(f"сырьё выгружено: {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main(sys.argv[1:])))
