# нетронутыми — их форматирует уже LightRAG в режиме naive.
AFM_SYSTEM_PROMPT = (
    _AFM_PROMPT_TEMPLATE
    .replace("{not_found_ru}", NOT_FOUND_RU)
    .replace("{not_found_kk}", NOT_FOUND_KK)
)
